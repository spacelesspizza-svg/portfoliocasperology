const NBSP = "\u00A0";

/** Короткие предлоги, союзы и частицы — неразрывный пробел перед следующим словом. */
const HANGING_WORDS = [
  "без",
  "близ",
  "в",
  "во",
  "вдоль",
  "вместо",
  "вне",
  "внутри",
  "вокруг",
  "вследствие",
  "для",
  "до",
  "за",
  "из",
  "изо",
  "из-за",
  "из-под",
  "к",
  "ко",
  "кроме",
  "между",
  "мимо",
  "на",
  "над",
  "надо",
  "не",
  "ни",
  "но",
  "о",
  "об",
  "обо",
  "около",
  "от",
  "ото",
  "перед",
  "передо",
  "по",
  "под",
  "подо",
  "после",
  "посреди",
  "при",
  "про",
  "против",
  "ради",
  "с",
  "со",
  "среди",
  "у",
  "через",
  "а",
  "и",
  "ли",
  "же",
  "бы",
  "как",
  "что",
  "это",
];

const sorted = [...HANGING_WORDS].sort((a, b) => b.length - a.length);
const pattern = new RegExp(
  `(^|[\\n\\s])(${sorted.map((w) => w.replace(/-/g, "\\-")).join("|")})([ \\t]+)(?=[а-яёА-ЯЁa-zA-Z0-9])`,
  "gi",
);

/** Переносит «висячие» предлоги на следующую строку (неразрывный пробел после них). */
export function fixHangingPrepositions(text: string): string {
  return text.replace(pattern, (_, before, word) => `${before}${word}${NBSP}`);
}
